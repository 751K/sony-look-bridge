#!/usr/bin/env python3
"""DaVinci Resolve DCTLs that follow the white balance: one per look and input gamut.

Each DCTL loads the look's six LUT variants (video_look.py ANCHORS: 2500, 3100, 4300, 4900, 5300 and
7500K) from its own folder and blends the two variants around the White Balance slider, linearly in
mired; below the first anchor and above the last it uses that variant alone.  The slider is the clip's
white balance as recorded by the camera.

Each variant carries the S-Gamut3.Cine -> camera RGB matrix measured at its white balance and the photo
look state the camera uses there.  The matrix changes non-monotonically with the white balance (it
turns around near 4300K), which three anchors could not follow: on the 2026-11-16 chart sweep, mired
interpolation between these six anchors stays within 0.54 ΔE2000 of each step's own matrix.

usage: make_dctl.py LUT_DIR [--out DIR]   (default: write next to the LUTs)
"""
from __future__ import annotations

import argparse
from pathlib import Path

from video_look import ANCHORS

LOOKS = ("ST", "PT", "NT", "VV", "VV2", "FL", "IN", "SH", "BW", "Sepia", "FL2", "FL3")
GAMUTS = ("SGamut3", "SGamut3Cine")
KELVINS = sorted(ANCHORS)
GRID = 65


def lut_name(gamut, look, suffix=""):
    return f"SonyA7M5_SLog3_{gamut}_{look}{suffix}_Rec709_G24_{GRID}.cube"


def dctl(gamut, look, lut_dir=""):
    path = lambda k: f"{lut_dir}{lut_name(gamut, look, f'-{k}K')}"
    luts = "\n".join(f"DEFINE_LUT(K{k}, {path(k)})" for k in KELVINS)
    segments = []
    for lo, hi in zip(KELVINS, KELVINS[1:]):
        segments.append(f"""    if (m >= {1e6 / hi:.4f}f) {{
        const float t = (m - {1e6 / hi:.4f}f) / ({1e6 / lo:.4f}f - {1e6 / hi:.4f}f);
        return _mix(APPLY_LUT(p_R, p_G, p_B, K{hi}), APPLY_LUT(p_R, p_G, p_B, K{lo}), t);
    }}""")
    gamut_name = gamut.replace('SGamut3Cine', 'S-Gamut3.Cine').replace('SGamut3', 'S-Gamut3')
    anchors = ", ".join(f"{k}K" for k in KELVINS)
    return f"""// Sony α7 V {look} Creative Look for S-Log3 / {gamut_name}, following the white balance.
// Sony Look Bridge, https://github.com/751K/sony-look-bridge (generated by video/make_dctl.py)
// Input: S-Log3 (10-bit CV / 1023).  Output: Rec.709 primaries, Gamma 2.4.
// Set White Balance to the white balance the clip was shot with.  The six LUTs ({anchors}) must
// sit next to this file; neighbouring LUTs are blended linearly in mired.

DEFINE_UI_PARAMS(kelvin, White Balance K, DCTLUI_SLIDER_FLOAT, 5600.0, 2000.0, 10000.0, 10.0)

{luts}

__DEVICE__ float3 transform(int p_Width, int p_Height, int p_X, int p_Y, float p_R, float p_G, float p_B)
{{
    const float m = 1.0e6f / _fmaxf(kelvin, 1000.0f);
    if (m >= {1e6 / KELVINS[0]:.4f}f) {{
        return APPLY_LUT(p_R, p_G, p_B, K{KELVINS[0]});
    }}
    if (m <= {1e6 / KELVINS[-1]:.4f}f) {{
        return APPLY_LUT(p_R, p_G, p_B, K{KELVINS[-1]});
    }}
{chr(10).join(segments)}
    return APPLY_LUT(p_R, p_G, p_B, K{KELVINS[-1]});
}}
"""


def dctl_name(gamut, look):
    return f"SonyA7M5_SLog3_{gamut}_{look}_Rec709_G24_WB.dctl"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("luts", type=Path)
    ap.add_argument("--out", type=Path)
    a = ap.parse_args()
    out = a.out or a.luts
    out.mkdir(parents=True, exist_ok=True)
    missing = [lut_name(g, l, f"-{k}K") for g in GAMUTS for l in LOOKS for k in KELVINS
               if not (a.luts / lut_name(g, l, f"-{k}K")).exists()]
    if missing:
        raise SystemExit(f"missing LUTs in {a.luts}: {missing[:3]} ...")
    for gamut in GAMUTS:
        for look in LOOKS:
            (out / dctl_name(gamut, look)).write_text(dctl(gamut, look), newline="\n")
    print(f"{len(GAMUTS) * len(LOOKS)} DCTLs -> {out}")


if __name__ == "__main__":
    main()
