#!/usr/bin/env python3
"""DaVinci Resolve DCTLs that follow the white balance: one per look and input gamut.

Each DCTL loads the look's three LUT variants (Warm, 4200K, Daylight; video_look.py) from its own
folder and blends their outputs by a White Balance slider, linearly in mired between anchors:

  3700K and below   Warm
  4640K             4200K     (the clip white balance the camera recorded under the 4200K chart light)
  5470K and above   Daylight

3700K and 5470K are where the camera's photo looks reach the full warm / daylight state
(docs/pipeline.md 4.3), moved to the clip white-balance scale: the clip and Camera Raw temperatures of
the three chart lights are linear in mired (docs/video.md).  The outputs of three anchors, not two,
are blended: Warm and Daylight alone are 1.9 ΔE2000 off at 4200K, the 4200K anchor 0.7.

usage: make_dctl.py LUT_DIR [--out DIR]   (default: write next to the LUTs)
"""
from __future__ import annotations

import argparse
from pathlib import Path

LOOKS = ("ST", "PT", "NT", "VV", "VV2", "FL", "IN", "SH", "BW", "Sepia", "FL2", "FL3")
GAMUTS = ("SGamut3", "SGamut3Cine")
WARM_K, MID_K, DAY_K = 3700.0, 4640.0, 5470.0
GRID = 65


def lut_name(gamut, look, suffix=""):
    return f"SonyA7M5_SLog3_{gamut}_{look}{suffix}_Rec709_G24_{GRID}.cube"


def dctl(gamut, look, lut_dir=""):
    path = lambda suffix: f"{lut_dir}{lut_name(gamut, look, suffix)}"
    return f"""// Sony α7 V {look} Creative Look for S-Log3 / {gamut.replace('SGamut3Cine', 'S-Gamut3.Cine').replace('SGamut3', 'S-Gamut3')}, following the white balance.
// Sony Look Bridge, https://github.com/751K/sony-look-bridge (generated by video/make_dctl.py)
// Input: S-Log3 (10-bit CV / 1023).  Output: Rec.709 primaries, Gamma 2.4.
// Set White Balance to the white balance the clip was shot with.  The three LUTs must sit next to
// this file.  Blend, linear in mired: Warm at {WARM_K:.0f}K and below, 4200K at {MID_K:.0f}K,
// Daylight at {DAY_K:.0f}K and above.

DEFINE_UI_PARAMS(kelvin, White Balance K, DCTLUI_SLIDER_FLOAT, 5600.0, 2000.0, 10000.0, 10.0)

DEFINE_LUT(WARM, {path("-Warm")})
DEFINE_LUT(MID, {path("-4200K")})
DEFINE_LUT(DAY, {path("")})

__DEVICE__ float3 transform(int p_Width, int p_Height, int p_X, int p_Y, float p_R, float p_G, float p_B)
{{
    const float m = 1.0e6f / _fmaxf(kelvin, 1000.0f);
    const float mWarm = 1.0e6f / {WARM_K:.1f}f;
    const float mMid = 1.0e6f / {MID_K:.1f}f;
    const float mDay = 1.0e6f / {DAY_K:.1f}f;
    if (m >= mWarm) {{
        return APPLY_LUT(p_R, p_G, p_B, WARM);
    }}
    if (m <= mDay) {{
        return APPLY_LUT(p_R, p_G, p_B, DAY);
    }}
    const float3 mid = APPLY_LUT(p_R, p_G, p_B, MID);
    if (m >= mMid) {{
        const float3 warm = APPLY_LUT(p_R, p_G, p_B, WARM);
        return _mix(mid, warm, (m - mMid) / (mWarm - mMid));
    }}
    const float3 day = APPLY_LUT(p_R, p_G, p_B, DAY);
    return _mix(day, mid, (m - mDay) / (mMid - mDay));
}}
"""


def dctl_name(gamut, look):
    return f"SonyA7M5_SLog3_{gamut}_{look}_Rec709_G24_WB.dctl"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("luts", type=Path)
    ap.add_argument("--out", type=Path)
    a = ap.parse_args()
    out = a.out or a.luts
    out.mkdir(parents=True, exist_ok=True)
    missing = [lut_name(g, l, s) for g in GAMUTS for l in LOOKS for s in ("", "-4200K", "-Warm")
               if not (a.luts / lut_name(g, l, s)).exists()]
    if missing:
        raise SystemExit(f"missing LUTs in {a.luts}: {missing[:3]} ...")
    for gamut in GAMUTS:
        for look in LOOKS:
            (out / dctl_name(gamut, look)).write_text(dctl(gamut, look), newline="\n")
    print(f"{len(GAMUTS) * len(LOOKS)} DCTLs -> {out}")


if __name__ == "__main__":
    main()
